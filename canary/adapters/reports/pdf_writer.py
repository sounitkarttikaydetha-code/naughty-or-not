"""
PDF Report Writer Adapter for Clearance Check Canary.
Renders formal PDF audit certificates with mandatory Canary banner & footer notices.
"""
import io
import time
from typing import Any, Dict

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

from canary.application.ports.report_writer import ReportWriterPort

CANARY_NOTICE = "Canary build — for evaluation only. Not for screening decisions."
PREPARED_BY = "Prepared by: Antigravity (AI assistant) — for review by Sounit Karttikay"


class CanaryPDFWriter(ReportWriterPort):
    """Generates PDF documents adhering to Part P and Canary notice rules."""

    def generate_pdf_report(self, data: Dict[str, Any]) -> bytes:
        buffer = io.BytesIO()

        def draw_canary_header_footer(canvas, doc):
            canvas.saveState()
            canvas.setFont("Helvetica-Bold", 8)
            canvas.setFillColor(colors.HexColor("#B71C1C"))

            # Header
            canvas.drawCentredString(A4[0] / 2.0, A4[1] - 30, CANARY_NOTICE)

            # Footer
            canvas.setFont("Helvetica", 7)
            canvas.setFillColor(colors.HexColor("#64748B"))
            canvas.drawString(40, 30, PREPARED_BY)
            canvas.drawRightString(A4[0] - 40, 30, f"Page {doc.page} | Clearance Check Canary v2.0.1")
            canvas.setFont("Helvetica-Bold", 7)
            canvas.setFillColor(colors.HexColor("#B71C1C"))
            canvas.drawCentredString(A4[0] / 2.0, 18, CANARY_NOTICE)
            canvas.restoreState()

        doc = SimpleDocTemplate(
            buffer,
            pagesize=A4,
            leftMargin=40,
            rightMargin=40,
            topMargin=50,
            bottomMargin=50,
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            "CanaryTitle",
            parent=styles["Heading1"],
            fontName="Helvetica-Bold",
            fontSize=16,
            leading=20,
            textColor=colors.HexColor("#1E3A5F"),
        )
        body_style = ParagraphStyle(
            "CanaryBody",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#0F172A"),
        )
        banner_style = ParagraphStyle(
            "BannerNotice",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#B71C1C"),
            alignment=1,
        )

        story = []

        # Banner Box
        banner_table = Table(
            [[Paragraph(CANARY_NOTICE, banner_style)]],
            colWidths=[A4[0] - 80],
        )
        banner_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#FFEBEE")),
            ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#EF9A9A")),
            ('TOPPADDING', (0, 0), (-1, -1), 6),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ]))
        story.append(banner_table)
        story.append(Spacer(1, 15))

        # Title
        story.append(Paragraph("Clearance Check Canary — Compliance Screening Certificate", title_style))
        story.append(Spacer(1, 8))

        # Metadata
        query = data.get("query", "—")
        ts = data.get("timestamp", time.strftime("%Y-%m-%d %H:%M:%SZ", time.gmtime()))
        gen_by = data.get("generated_by", "Screener")

        meta_data = [
            ["Subject / Target:", query, "Date / Time (UTC):", ts],
            ["Generated By:", gen_by, "Engine Version:", "2.0.1-canary.1"],
            ["Legal Disclaimer:", "For evaluation only; not for actual screening decisions.", "", ""],
        ]
        meta_table = Table(meta_data, colWidths=[110, 150, 110, 150])
        meta_table.setStyle(TableStyle([
            ('FONTNAME', (0, 0), (-1, -1), 'Helvetica'),
            ('FONTSIZE', (0, 0), (-1, -1), 8),
            ('TEXTCOLOR', (0, 0), (-1, -1), colors.HexColor("#0F172A")),
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(meta_table)
        story.append(Spacer(1, 15))

        # Screening Results Table
        headers = ["Source List", "Result Tier", "Score", "Matched Name", "Record ID"]
        rows = [headers]
        lists = data.get("lists", {})
        for l_name, hit in lists.items():
            if isinstance(hit, dict):
                tier = hit.get("tier", "NO_MATCH")
                score = f"{float(hit.get('score', 0.0)):.4f}"
                m_name = hit.get("matched_name", "—")
                s_id = hit.get("source_id", "—")
            else:
                tier = getattr(hit, "tier", "NO_MATCH")
                score = f"{getattr(hit, 'score', 0.0):.4f}"
                m_name = getattr(hit, "matched_name", "—")
                s_id = getattr(hit, "source_id", "—")

            rows.append([l_name.upper(), tier, score, m_name, s_id])

        res_table = Table(rows, colWidths=[90, 120, 50, 190, 70])
        res_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#1E3A5F")),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, 0), 8),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 5),
            ('TOPPADDING', (0, 0), (-1, 0), 5),
            ('FONTNAME', (0, 1), (-1, -1), 'Helvetica'),
            ('FONTSIZE', (0, 1), (-1, -1), 8),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
        ]))
        story.append(res_table)

        doc.build(story, onFirstPage=draw_canary_header_footer, onLaterPages=draw_canary_header_footer)
        return buffer.getvalue()

    def generate_excel_report(self, data: Dict[str, Any]) -> bytes:
        # Default delegate to excel adapter
        from canary.adapters.reports.excel_writer import CanaryExcelWriter
        writer = CanaryExcelWriter()
        return writer.generate_excel_report(data)
