"""
Excel Report Writer Adapter for Clearance Check Canary.
Generates multi-sheet compliance workbooks with prominent Canary evaluation banners.
"""
import io
import time
from typing import Any, Dict

import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side

from canary.application.ports.report_writer import ReportWriterPort

CANARY_NOTICE = "Canary build — for evaluation only. Not for screening decisions."
PREPARED_BY = "Prepared by: Antigravity (AI assistant) — for review by Sounit Karttikay"


class CanaryExcelWriter(ReportWriterPort):
    """Generates Excel workbooks adhering to Part P and Canary notice rules."""

    def generate_excel_report(self, data: Dict[str, Any]) -> bytes:
        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = "Screening Summary"

        # Styles
        banner_font = Font(name="Segoe UI", size=10, bold=True, color="B71C1C")
        banner_fill = PatternFill(start_color="FFEBEE", end_color="FFEBEE", fill_type="solid")

        header_font = Font(name="Segoe UI", size=11, bold=True, color="FFFFFF")
        header_fill = PatternFill(start_color="1E3A5F", end_color="1E3A5F", fill_type="solid")

        bold_font = Font(name="Segoe UI", size=9, bold=True, color="0F172A")
        cell_font = Font(name="Segoe UI", size=9, color="0F172A")

        thin_side = Side(style="thin", color="CBD5E1")
        cell_border = Border(top=thin_side, left=thin_side, right=thin_side, bottom=thin_side)

        # 1. Canary Banner (Row 1 & 2)
        ws.merge_cells("A1:E1")
        cell_a1 = ws["A1"]
        cell_a1.value = CANARY_NOTICE
        cell_a1.font = banner_font
        cell_a1.fill = banner_fill
        cell_a1.alignment = Alignment(horizontal="center", vertical="center")

        ws.merge_cells("A2:E2")
        cell_a2 = ws["A2"]
        cell_a2.value = PREPARED_BY
        cell_a2.font = Font(name="Segoe UI", size=8, italic=True, color="64748B")
        cell_a2.alignment = Alignment(horizontal="center", vertical="center")

        # 2. Metadata (Rows 4 to 6)
        query = data.get("query", "—")
        ts = data.get("timestamp", time.strftime("%Y-%m-%d %H:%M:%SZ", time.gmtime()))
        gen_by = data.get("generated_by", "Screener")

        meta = [
            ("Target Entity:", query, "Date / Time (UTC):", ts),
            ("Generated By:", gen_by, "Engine Version:", "2.0.1-canary.1"),
            ("Status:", "EVALUATION ONLY", "Notice:", "Not for screening decisions"),
        ]
        for row_idx, r in enumerate(meta, start=4):
            ws.cell(row=row_idx, column=1, value=r[0]).font = bold_font
            ws.cell(row=row_idx, column=2, value=r[1]).font = cell_font
            ws.cell(row=row_idx, column=3, value=r[2]).font = bold_font
            ws.cell(row=row_idx, column=4, value=r[3]).font = cell_font

        # 3. Table Headers (Row 8)
        cols = ["Source List", "Result Tier", "Match Score", "Matched Name", "Source Record ID"]
        for col_idx, col_name in enumerate(cols, start=1):
            c = ws.cell(row=8, column=col_idx, value=col_name)
            c.font = header_font
            c.fill = header_fill
            c.alignment = Alignment(horizontal="left", vertical="center")
            c.border = cell_border

        # 4. Table Data (Row 9+)
        lists = data.get("lists", {})
        curr_row = 9
        for l_name, hit in lists.items():
            if isinstance(hit, dict):
                tier = hit.get("tier", "NO_MATCH")
                score = round(float(hit.get("score", 0.0)), 4)
                m_name = hit.get("matched_name", "—")
                s_id = hit.get("source_id", "—")
            else:
                tier = getattr(hit, "tier", "NO_MATCH")
                score = round(float(getattr(hit, "score", 0.0)), 4)
                m_name = getattr(hit, "matched_name", "—")
                s_id = getattr(hit, "source_id", "—")

            row_vals = [l_name.upper(), tier, score, m_name, s_id]
            for col_idx, val in enumerate(row_vals, start=1):
                c = ws.cell(row=curr_row, column=col_idx, value=val)
                c.font = cell_font
                c.border = cell_border
            curr_row += 1

        # Adjust column widths
        widths = [18, 25, 14, 40, 20]
        for idx, w in enumerate(widths, start=1):
            col_letter = openpyxl.utils.get_column_letter(idx)
            ws.column_dimensions[col_letter].width = w

        buffer = io.BytesIO()
        wb.save(buffer)
        return buffer.getvalue()

    def generate_pdf_report(self, data: Dict[str, Any]) -> bytes:
        from canary.adapters.reports.pdf_writer import CanaryPDFWriter
        return CanaryPDFWriter().generate_pdf_report(data)
